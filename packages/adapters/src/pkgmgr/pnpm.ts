import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { BASELINE, type RuntimeInfo } from '@dda/spec';

import { runCommand, fileExists } from '../process/runner';
import type { AppPaths } from '../paths';
import { nodeExe, npmCliJs, pnpmCliJs } from '../paths';

export interface PnpmOptions {
  registry: string;
  log: (m: string) => void;
}

/** pnpm is installed into our own prefix via the bundled npm; nothing global is touched. */
export async function ensurePnpm(paths: AppPaths, options: PnpmOptions): Promise<RuntimeInfo> {
  const cli = pnpmCliJs(paths);
  const exe = nodeExe(paths);
  await mkdir(paths.pnpmPrefix, { recursive: true });

  if (await fileExists(cli)) {
    const { stdout } = await runCommand({ exePath: exe, args: [cli, '--version'], timeoutMs: 30_000 });
    const version = stdout.trim();
    if (version.startsWith(BASELINE.pnpm.version)) {
      return { id: 'pnpm', installed: true, version, path: cli };
    }
    options.log(`已存在的 pnpm ${version} 与锁定版本 ${BASELINE.pnpm.version} 不一致，重新安装`);
  }

  options.log(`安装 pnpm@${BASELINE.pnpm.version} 到私有前缀`);
  await runCommand({
    exePath: exe,
    args: [
      npmCliJs(paths),
      'install',
      '--prefix',
      paths.pnpmPrefix,
      `pnpm@${BASELINE.pnpm.version}`,
      '--registry',
      options.registry,
      '--no-audit',
      '--no-fund',
      '--loglevel=error',
    ],
    timeoutMs: 10 * 60_000,
  });

  const { stdout } = await runCommand({ exePath: exe, args: [cli, '--version'], timeoutMs: 30_000 });
  return { id: 'pnpm', installed: true, version: stdout.trim(), path: cli };
}

/**
 * `dsh plugin` forwards arguments to `pnpm` found on PATH. Node cannot spawn a `.cmd`
 * without a shell, so we generate a tiny shim that calls our pinned pnpm entry point.
 */
export async function writePnpmShim(paths: AppPaths): Promise<string> {
  const binDir = join(paths.root, 'bin');
  await mkdir(binDir, { recursive: true });
  const target = pnpmCliJs(paths);
  const shim = [
    '@echo off',
    'rem generated by DeepSeekDeployAssistant - do not edit',
    `"%~dp0..\\runtimes\\node\\${BASELINE.node.version}\\node.exe" "${target}" %*`,
    '',
  ].join('\r\n');
  await writeFile(join(binDir, 'pnpm.cmd'), shim, 'utf8');
  return binDir;
}
